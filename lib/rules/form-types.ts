/**
 * סוג הטופס מתוך השם (דן, 21/10: "תבניות שכבר אפשר לשלוח לפי סוג התבנית").
 * הטפסים בתיקיית "מסמכי מערכת" נקראים לפי מה שהם — "כתב הסמכה - טפחות", "חיווי אשראי - לווה 1"…
 * הסוג מאפשר לבחור "כל כתבי ההסמכה" או "הסכמה לנתוני אשראי" של גוף אחד בלי לחפש קובץ-קובץ.
 * הסדר חשוב: "ייפוי כוח ליועץ והסכמה לנתוני אשראי" הוא כתב הסמכה; "אישור תנאי שימוש וחיווי אשראי" — חיווי;
 * "תצהיר הכנסות" — אישור הכנסות, לא תצהיר. טופס שהשם שלו לא אומר כלום ("טופס הסכמת לקוח") — הסוג מהשדות המוכנים.
 */
export const FORM_TYPES = {
  poa: 'כתב הסמכה ליועץ',
  credit_data: 'הסכמה לנתוני אשראי',
  credit_check: 'חיווי אשראי',
  privacy: 'ויתור סודיות',
  kyc: 'הכר את הלקוח',
  application: 'בקשה להלוואה',
  income: 'אישור הכנסות',
  declaration: 'תצהירים ואישורים',
  other: 'טפסים נוספים',
} as const
export type FormType = keyof typeof FORM_TYPES

const RULES: [RegExp, FormType][] = [
  [/הסמכה|הרשאה\s*ליועץ|יי?פוי\s*כו?ח|authorization/i, 'poa'],
  [/חיווי/, 'credit_check'],
  [/נתוני\s*אשראי|דו["״]?ח\s*(?:נתוני\s*)?אשראי/, 'credit_data'],
  [/ויתור\s*(?:על\s*)?סודיות/, 'privacy'],
  [/הכר\s*את\s*הלקוח|שאלון|זיהוי\s*פנים|הערכת\s*לווים/, 'kyc'],
  [/בקשה\s*ל(?:קבלת\s*)?(?:הלוואה|משכנתא|אישור)|טופס\s*בקשה/, 'application'],
  [/(?:אישור|תצהיר)\s*הכנסות/, 'income'],
  [/תצהיר|אישור\s*מהנדס|הסכמת\s*יזם|זום|דף\s*עמלות|קיט\s*מסמכים/, 'declaration'],
]

export function formTypeOf(name: string): FormType {
  const s = String(name ?? '').replace(/\s+/g, ' ')
  for (const [re, t] of RULES) if (re.test(s)) return t
  return 'other'
}
